# frozen_string_literal: true

require "yaml"
require "date"
require "json"
require "erb"

require_relative "../query/kind_census"
require_relative "../query/list"

module Nabu
  module Ops
    # The site's single-source-of-truth projection (P58 rider, owner
    # commission): every registry-derivable fact a site page cites lives in
    # site/_data/*.yml, GENERATED here, and the pages read it through
    # Liquid — so a new research desk or a fresh census appears everywhere
    # by regeneration, never by chasing prose. (The AxisPages stance one
    # level up: pages loop over data; hand-written text carries only what
    # no registry knows.)
    #
    # Two files, two natures:
    #
    #   * desks.yml — PURE registry projection (config/axes.yml order,
    #     persona split into name/blurb at the em-dash, public member
    #     counts). Deterministic from the registries alone — the drift
    #     guard (test/site/site_data_test.rb) regenerates it in memory and
    #     fails the suite the day the committed copy goes stale.
    #   * census.yml — LIVE catalog/fulltext numbers, stamped as_of. Dated
    #     by nature, refreshed at every gate (site/MAINTENANCE.md duty 1);
    #     the guard pins its SHAPE, never its dated values.
    #   * dates.yml / kinds.yml / sources.yml — further live projections of
    #     the same nature (sources.yml: the per-source grain, see #sources;
    #     its shelf totals follow the hand-curated shelf_members.yml).
    #   * mcp.yml — pure like desks.yml (see #mcp).
    class SiteData
      DESKS_FILE = "desks.yml"
      CENSUS_FILE = "census.yml"
      # P81-1 (C-6): the chronological census behind /dates/ — the same
      # Query::List#by_date_census the CLI's `list --by-date` renders.
      DATES_FILE = "dates.yml"
      # P100-6: the kind-axis class board behind /kinds/ — the same
      # Query::KindCensus the CLI's `nabu kind census` renders.
      KINDS_FILE = "kinds.yml"

      # The per-source grain behind /library/'s collection table, /sources/'
      # holdings column and /quickstart/'s disk figures: one row per live
      # public source (source_stats, the sanctioned per-source reader that
      # `nabu status` renders), the shelf totals summed over the curated
      # shelf map, and du-measured canonical sizes.
      SOURCES_FILE = "sources.yml"
      # HAND-curated input (not generated): which sources each /library/
      # table row sums. Lives beside the data it shapes, like
      # language_notes.yml.
      SHELF_MEMBERS_FILE = "shelf_members.yml"

      # Century rows name at most this many sources (+n more) — the CLI cap.
      DATES_SOURCES = 4

      # The headline languages table (languages.md) shows this many; index.md
      # reads only [0]/[1]. One SSOT list, sliced per page in Liquid.
      TOP_LANGUAGES = 16

      GENERATED_NOTE = "GENERATED by `rake site:data` (Nabu::Ops::SiteData) — do not hand-edit; " \
                       "regenerate at every gate."

      # The MCP page's projection (site/mcp.md, site/tools.md) — pure, like
      # desks.yml: the server's own tool registry, server.json's released
      # demo tag, and the demo slice's license table.
      MCP_FILE = "mcp.yml"

      # The canonical-tree measurement, through the sanctioned Shell: ONE
      # `du -sk` over every child of the tree (one walk, ~20 s on the full
      # library — paid only inside site:data, never by a reader). Returns
      # { child path => kilobytes }. Injectable so tests never shell out.
      module Disk
        module_function

        def tree_kb(dir)
          children = Dir.children(dir).sort.map { |name| File.join(dir, name) }
          return {} if children.empty?

          Nabu::Shell.run("du", "-sk", *children).lines.to_h do |line|
            kb, path = line.chomp.split("\t", 2)
            [path, kb.to_i]
          end
        end
      end

      def initialize(registry:, data_dir:, catalog_path: nil, fulltext_path: nil, canonical_dir: nil,
                     disk: Disk, as_of: Date.today, project_root: Config::PROJECT_ROOT)
        @registry = registry
        @project_root = project_root
        @data_dir = data_dir
        @catalog_path = catalog_path
        @fulltext_path = fulltext_path
        @canonical_dir = canonical_dir
        @disk = disk
        @as_of = as_of
      end

      # The registry projection, as plain data (the drift guard compares
      # this against the committed file).
      def desks
        @registry.axes.each_axis.map do |axis|
          name, blurb = split_persona(axis.persona)
          { "slug" => axis.name, "persona" => name, "blurb" => blurb,
            "members" => @registry.public_axis_members(axis.name).size }
        end
      end

      # The live numbers the site's prose cites. Catalog required;
      # fulltext required too (the publishing box has both — a worktree
      # run points env overrides at the main checkout, the site:axes
      # pattern).
      def census
        catalog = Store.connect(@catalog_path, readonly: true)
        fulltext = Store.connect(@fulltext_path, readonly: true)
        live_docs = catalog[:documents].where(Sequel[:documents][:withdrawn] => false)
        languages = live_docs.exclude(Sequel[:documents][:language] => nil).distinct.select(:language).count
        top = live_docs.exclude(Sequel[:documents][:language] => nil)
                       .join(:passages, document_id: :id).where(Sequel[:passages][:withdrawn] => false)
                       .group(Sequel[:documents][:language])
                       .select { [documents[:language].as(:language), count.function.*.as(:passages)] }
                       .order(Sequel.desc(:passages)).limit(TOP_LANGUAGES).all
        tiers = fulltext[:passage_lemmas].group_and_count(:tier).as_hash(:tier, :count)
        gold = tiers["gold"].to_i
        silver = tiers["silver"].to_i
        silver_langs = fulltext[:passage_lemmas].where(tier: "silver").distinct.select(:language).count
        documents = live_docs.count
        passages = catalog[:passages].where(withdrawn: false).count
        entries = catalog[:dictionary_entries].where(withdrawn: false).count
        reg = registry_breakdown
        kind = kind_headline(catalog)
        {
          # Liquid cannot comma- or million-format, so every number the
          # prose cites ships BOTH raw and display-ready. This hash is the
          # single source of truth for every headline figure the site
          # states — a page that hardcodes one instead is the drift this
          # census exists to kill (test/site/site_prose_ssot_test.rb).
          "as_of" => @as_of.strftime("%-d %B %Y"),
          "documents" => documents, "documents_display" => self.class.commas(documents),
          "passages" => passages, "passages_display" => self.class.commas(passages),
          "language_codes" => languages,
          # The registry shape (config/sources.yml): rows split by kind, and
          # the wired-source count the "N sources live" prose cites.
          "registry_rows" => reg[:rows],
          "corpus_sources" => reg[:sources],
          "live_sources" => reg[:live_sources],
          "local_shelves" => reg[:shelves],
          "feature_modules" => reg[:modules],
          "top_languages" => top.map do |row|
            { "code" => row[:language], "passages" => row[:passages],
              "millions" => self.class.millions(row[:passages]) }
          end,
          "dictionary_entries" => entries, "dictionary_entries_display" => self.class.commas(entries),
          "dictionary_shelves" => catalog[:dictionaries].count,
          # P106-3 (the multi-shelf dictionary ruling, generalization 2): the dictionary-group census — shelves
          # grouped by resolved lect node (dictionary_stats, migration
          # 036), plus the honestly-censused count of language codes the
          # registry cannot yet place. Zero on a pre-036/underived
          # catalog — the guard test treats that as the drift it is.
          "dictionary_lects" =>
            dictionary_stats_column(catalog) { |ds| ds.exclude(lect: nil).distinct.select(:lect).count },
          "dictionary_unresolved_codes" =>
            dictionary_stats_column(catalog) { |ds| ds.where(lect: nil).distinct.select(:language).count },
          # The etym cognate-list code universe (languages.md cites it; it
          # drifted from a hardcoded 803 to 1,131 before joining the SSOT —
          # the ko/cmn lesson, P105 follow-up).
          "etym_codes" => catalog[:dictionary_reflexes].distinct.select(:lang_code).count,
          "gold_lemmas" => gold, "gold_lemmas_display" => self.class.commas(gold),
          "gold_lemmas_m" => self.class.millions(gold),
          "gold_languages" => fulltext[:reflex_root_stats].count,
          "silver_lemmas" => silver, "silver_lemmas_display" => self.class.commas(silver),
          "silver_lemmas_m" => self.class.millions(silver),
          "silver_languages" => silver_langs,
          "desks" => @registry.axes.size,
          # The kind axis' headline (P100-6): class families attested,
          # classified-document total, and the classified share of the
          # kind-eligible library (classified + unclassified live docs).
          "kind_class_count" => kind[:classes],
          "kind_documents" => kind[:documents],
          "kind_documents_display" => self.class.commas(kind[:documents]),
          "kind_coverage_pct" => kind[:coverage],
          # P118-R5: the licensing prose's "roughly N% of documents are
          # public-domain or attribution-class" (index, faq, sources) — it
          # had rotted from 99% to 96% as nc-class growth landed.
          "redistributable_pct" => self.class.redistributable_pct(catalog)
        }
      ensure
        catalog&.disconnect
        fulltext&.disconnect
      end

      # The registry shape as counts (config/sources.yml): total rows split
      # by kind (source / shelf / feature module), plus the wired-source
      # count. Pure registry data — deterministic, no catalog read.
      # The dictionary_stats read with the pre-036 guard: 0 when the
      # table is absent or never derived (honest, and the site guard
      # test flags it — the census must be derived before site:refresh).
      def dictionary_stats_column(catalog)
        return 0 unless catalog.table_exists?(:dictionary_stats)

        yield catalog[:dictionary_stats]
      end

      #
      # The rows split counts every registry row (the registry's SHAPE); the
      # live-source figure — the "N sources live" holdings claim — counts
      # only PUBLIC wired sources: grant-gated blocked holdings are never
      # advertised and public census surfaces never count them (the
      # SourceRegistry availability contract, owner ruling 2026-07-24;
      # P118-R5 closed the gap where they had been counted).
      def registry_breakdown
        entries = @registry.each_source.to_a
        { rows: entries.size,
          sources: entries.count(&:source?),
          shelves: entries.count(&:shelf?),
          modules: entries.count(&:feature_module?),
          live_sources: entries.count { |entry| entry.source? && entry.wired && entry.public? } }
      end

      # The share (integer percent, rounded) of live documents whose
      # EFFECTIVE license class — the per-document override where one
      # exists, else the source's class — is open or attribution: the
      # freely redistributable part of the library. 0 on an empty catalog.
      def self.redistributable_pct(catalog)
        live = catalog[:documents].join(:sources, id: :source_id)
                                  .where(Sequel[:documents][:withdrawn] => false)
        total = live.count
        return 0 unless total.positive?

        effective = Sequel.function(:coalesce, Sequel[:documents][:license_override],
                                    Sequel[:sources][:license_class])
        free = live.where(effective => %w[open attribution]).count
        ((free * 100.0) / total).round
      end

      # The dates page's data (P81-1, C-6): the chronological census as
      # Liquid-ready rows — every number both raw and display, the source
      # breakdown pre-joined (Liquid cannot comma-format or cap).
      def dates
        catalog = Store.connect(@catalog_path, readonly: true)
        census = Query::List.new(catalog: catalog).by_date_census
        {
          "as_of" => @as_of.strftime("%-d %B %Y"),
          "dated_documents" => census.dated_documents,
          "dated_documents_display" => self.class.commas(census.dated_documents),
          "total_documents" => census.total_documents,
          "total_documents_display" => self.class.commas(census.total_documents),
          "coverage_percent" => coverage_percent(census),
          "multi_century" => census.multi_century,
          "multi_century_display" => self.class.commas(census.multi_century),
          "centuries" => census.buckets.map { |bucket| century_row(bucket) }
        }
      ensure
        catalog&.disconnect
      end

      # The kinds page's data (P100-6): the kind-axis class board as
      # Liquid-ready rows — head-grain classes ranked by document spread,
      # the honesty buckets (unknown / unmapped) beside — never inside —
      # the classes, the unclassified remainder announced. A catalog
      # predating migration 032 (no kind_stats) yields the honest empty
      # board.
      def kinds
        catalog = Store.connect(@catalog_path, readonly: true)
        report = Query::KindCensus.new(catalog: catalog).run
        { "as_of" => @as_of.strftime("%-d %B %Y") }.merge(kind_board(report))
      ensure
        catalog&.disconnect
      end

      # The per-source data (sources.yml): one row per live PUBLIC source,
      # slug-ordered (blocked holdings never reach a public census surface),
      # the /library/ shelf totals summed over the curated shelf map, and —
      # when a canonical tree is given — the du-measured disk figures
      # quickstart cites. Liquid cannot comma-format, so every figure ships
      # raw and display-ready.
      def sources
        catalog = Store.connect(@catalog_path, readonly: true)
        sizes = canonical_sizes
        rows = source_rows(catalog, sizes)
        { "as_of" => @as_of.strftime("%-d %B %Y"), "sources" => rows,
          "shelves" => shelf_rows(rows), "disk" => disk_totals(sizes) }
      ensure
        catalog&.disconnect
      end

      # Kilobytes as the quickstart prose states sizes (binary units, as du
      # counts): whole MB below a gigabyte, one decimal below ten GB, whole
      # GB above.
      def self.disk_display(kilobytes)
        mb = kilobytes / 1024.0
        return "<1 MB" if mb < 1
        return "#{mb.round} MB" if mb < 1024

        gb = mb / 1024
        gb < 10 ? "#{gb.round(1)} GB" : "#{gb.round} GB"
      end

      def self.commas(number)
        number.to_s.gsub(/(\d)(?=(\d{3})+\z)/, '\1,')
      end

      def self.millions(number)
        (number / 1_000_000.0).round(1).to_s
      end

      # The MCP page's data, deterministic from code + config alone (the
      # drift guard regenerates it in memory). Every install surface is
      # derived from ONE launch command naming the RELEASED image tag
      # (server.json's version, the demo-publish rail's SSOT) — never the
      # moving :latest. Tool rows carry the server's own name + title (the
      # MCP display name tools/list serves), so the page's list and count
      # are the registry's, never a hand number. The license table is the
      # demo build's plan (demo set + core + requires closure) with each
      # source's manifest license — exactly what the image's
      # demo-census.json enumerates.
      def mcp
        # A READ of the published image's number (nabu_version: nil skips
        # the release-sync gate — that gate guards PUBLISHING; the site
        # must describe the image that is live right now).
        version = DemoPublish.version(root: @project_root, nabu_version: nil)
        image = "#{DemoPublish::IMAGE}:#{version}"
        launch = { "command" => "docker", "args" => ["run", "-i", "--rm", image] }
        launch_json = JSON.generate(launch)
        cursor_config = ERB::Util.url_encode([launch_json].pack("m0"))
        {
          "version" => version,
          "image" => image,
          "image_repo" => DemoPublish::IMAGE,
          "protocol_version" => MCP::Server::PROTOCOL_VERSION,
          "tool_count" => MCP::Tools::TOOLS.size,
          "tools" => MCP::Tools::TOOLS.map { |name, tool| { "name" => name, "title" => tool.fetch(:title) } },
          "client_config" => JSON.pretty_generate("mcpServers" => { "nabu" => launch }),
          "verify_command" => mcp_verify_command(image),
          "vscode_install_url" =>
            "vscode:mcp/install?#{ERB::Util.url_encode(JSON.generate({ 'name' => 'nabu' }.merge(launch)))}",
          "vscode_redirect_url" =>
            "https://vscode.dev/redirect/mcp/install?name=nabu&config=#{ERB::Util.url_encode(launch_json)}",
          "cursor_install_url" => "cursor://anysphere.cursor-deeplink/mcp/install?name=nabu&config=#{cursor_config}",
          "cursor_redirect_url" => "https://cursor.com/install-mcp?name=nabu&config=#{cursor_config}",
          "koyeb_deploy_url" => "https://app.koyeb.com/deploy?type=docker&name=nabu-demo&image=#{image}" \
                                "&instance_type=free&ports=8080;http;/&env[PORT]=8080" \
                                "&command=bin/nabu&args=mcp&args=--http",
          "demo_sources" => demo_license_rows
        }
      end

      # Write the six generated files. Returns the paths written.
      def generate!
        FileUtils.mkdir_p(@data_dir)
        [write(DESKS_FILE, desks), write(CENSUS_FILE, census),
         write(DATES_FILE, dates), write(KINDS_FILE, kinds),
         write(SOURCES_FILE, sources), write(MCP_FILE, mcp)]
      end

      # THE public-listing rule, shared with the /sources/ table generator
      # (SourcesTable): wired corpus sources only, grant-gated blocked
      # holdings never — so the holdings data and the table's rows can never
      # disagree about who is listed.
      def self.live_public_slugs(registry)
        registry.each_source.select { |entry| entry.source? && entry.wired && entry.public? }.map(&:slug).sort
      end

      def self.split_persona(persona)
        name, blurb = persona.split(/\s+[—–]\s+/, 2)
        [name.to_s.strip, blurb.to_s.strip.sub(/\.\z/, "")]
      end

      private

      def split_persona(persona) = self.class.split_persona(persona)

      # The stdio handshake a user pipes into the image to see it answer:
      # initialize, the initialized notification, tools/list (the server
      # refuses tools/list before initialize).
      def mcp_verify_command(image)
        messages = [
          { "jsonrpc" => "2.0", "id" => 1, "method" => "initialize",
            "params" => { "protocolVersion" => MCP::Server::PROTOCOL_VERSION, "capabilities" => {},
                          "clientInfo" => { "name" => "check", "version" => "1" } } },
          { "jsonrpc" => "2.0", "method" => "notifications/initialized" },
          { "jsonrpc" => "2.0", "id" => 2, "method" => "tools/list" }
        ]
        quoted = messages.map { |message| "'#{JSON.generate(message)}'" }.join(" \\\n  ")
        "printf '%s\\n' \\\n  #{quoted} \\\n  | docker run -i --rm #{image}"
      end

      # Demo-set sources first (the texts and the dictionary shelf, in
      # DemoBuild order), then the core instruments the plan pulls in.
      def demo_license_rows
        demo = DemoBuild::DEMO_SOURCES.map(&:slug)
        plan = DemoBuild.plan_for(registry: @registry)
        (demo + (plan - demo)).select { |slug| plan.include?(slug) }.map do |slug|
          manifest = @registry[slug].manifest
          { "slug" => slug, "role" => demo.include?(slug) ? "demo" : "instrument",
            "name" => manifest.name, "license_class" => manifest.license_class,
            "license" => manifest.license, "upstream_url" => manifest.upstream_url }
        end
      end

      def coverage_percent(census)
        census.total_documents.positive? ? (census.dated_documents * 100) / census.total_documents : 0
      end

      def century_row(bucket)
        shown = bucket.sources.first(DATES_SOURCES)
                      .map { |slug, count| "#{slug} #{self.class.commas(count)}" }
        tail = bucket.sources.size - DATES_SOURCES
        shown << "+#{tail} more" if tail.positive?
        { "label" => bucket.label, "documents" => bucket.documents,
          "documents_display" => self.class.commas(bucket.documents),
          "sources" => shown.join(" · ") }
      end

      # The census' kind headline off the same open catalog handle: class
      # families attested, classified-doc total, and the classified share
      # (integer percent, the dates-coverage convention). Degrades to
      # zeros on a catalog without kind_stats.
      def kind_headline(catalog)
        report = Query::KindCensus.new(catalog: catalog).run
        documents = report&.classified_documents.to_i
        total = documents + report&.unclassified_documents.to_i
        { classes: report&.classes&.size.to_i,
          documents: documents,
          coverage: total.positive? ? (documents * 100) / total : 0 }
      end

      def kind_board(report)
        return { "classes" => [] }.merge(kind_buckets(nil)) if report.nil?

        classes = report.classes.map do |row|
          { "head" => row.head, "documents" => row.documents,
            "documents_display" => self.class.commas(row.documents),
            "sources" => row.sources }
        end
        { "classes" => classes }.merge(kind_buckets(report))
      end

      def kind_buckets(report)
        %w[unknown unmapped unclassified].each_with_object(
          "unclassified_sources" => report&.unclassified_sources.to_i
        ) do |bucket, hash|
          count = report&.public_send(:"#{bucket}_documents").to_i
          hash["#{bucket}_documents"] = count
          hash["#{bucket}_documents_display"] = self.class.commas(count)
        end
      end

      def live_public_slugs = self.class.live_public_slugs(@registry)

      def source_rows(catalog, sizes)
        meta = catalog[:sources].select(:id, :slug, :name, :license_class).to_hash(:slug)
        stats = Store::SourceStats.available?(catalog) ? catalog[Store::SourceStats::TABLE].to_hash(:source_id) : {}
        entries = entry_counts(catalog)
        live_public_slugs.to_h do |slug|
          source = meta[slug] || {}
          stat = stats[source[:id]] || {}
          row = source_row(source, slug: slug, documents: stat[:live_documents].to_i,
                                   passages: stat[:live_passages].to_i, entries: entries[source[:id]].to_i)
          kb = sizes[slug]
          row["canonical_display"] = self.class.disk_display(kb) if kb
          [slug, row]
        end
      end

      # Live dictionary entries per source id.
      def entry_counts(catalog)
        catalog[:dictionary_entries].join(:dictionaries, id: :dictionary_id)
                                    .where(Sequel[:dictionary_entries][:withdrawn] => false)
                                    .group_and_count(Sequel[:dictionaries][:source_id].as(:source_id))
                                    .as_hash(:source_id, :count)
      end

      def source_row(source, slug:, documents:, passages:, entries:)
        { "name" => source[:name] || slug, "license_class" => source[:license_class],
          "documents" => documents, "documents_display" => self.class.commas(documents),
          "passages" => passages, "passages_display" => self.class.commas(passages),
          "entries" => entries, "entries_display" => self.class.commas(entries),
          "holdings" => holdings(documents, passages, entries) }
      end

      # The sources page's one-cell summary of what the catalog holds.
      def holdings(documents, passages, entries)
        parts = []
        if documents.positive?
          parts << "#{self.class.commas(documents)} documents / #{self.class.commas(passages)} passages"
        end
        parts << "#{self.class.commas(entries)} entries" if entries.positive?
        parts.empty? ? "—" : parts.join(" · ")
      end

      # The /library/ table rows' totals over the curated shelf map. A slug
      # the map names but the rows lack sums as zero (the drift guard in
      # test/site/site_data_test.rb names it).
      def shelf_rows(rows)
        path = File.join(@data_dir, SHELF_MEMBERS_FILE)
        members = File.exist?(path) ? YAML.safe_load_file(path) || {} : {}
        members.to_h do |id, slugs|
          documents = slugs.sum { |slug| rows.dig(slug, "documents").to_i }
          passages = slugs.sum { |slug| rows.dig(slug, "passages").to_i }
          [id, { "sources" => slugs, "documents" => documents, "documents_display" => self.class.commas(documents),
                 "passages" => passages, "passages_display" => self.class.commas(passages),
                 "size_display" => "#{self.class.commas(documents)} / #{self.class.commas(passages)}" }]
        end
      end

      # { slug => kilobytes } for every child of the canonical tree; empty
      # without a tree (no tree, no size claim).
      def canonical_sizes
        return {} unless @canonical_dir

        @disk.tree_kb(@canonical_dir).transform_keys { |path| File.basename(path) }
      end

      # The quickstart headline sizes: the whole canonical tree, the derived
      # databases beside the catalog, and the quickstart-tagged starter set.
      def disk_totals(sizes)
        return {} if sizes.empty?

        starter = @registry.each_source.select(&:quickstart).sum { |entry| sizes[entry.slug].to_i }
        derived = Dir.glob(File.join(File.dirname(@catalog_path), "*.sqlite3")).sum { |f| File.size(f) } / 1024
        { "canonical_display" => self.class.disk_display(sizes.values.sum),
          "derived_display" => self.class.disk_display(derived),
          "starter_display" => self.class.disk_display(starter) }
      end

      def write(name, data)
        path = File.join(@data_dir, name)
        File.write(path, "# #{GENERATED_NOTE}\n#{YAML.dump(data)}")
        path
      end
    end
  end
