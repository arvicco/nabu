# frozen_string_literal: true

require "yaml"
require "fileutils"

module Nabu
  module Ops
    # The /sources/ corpus table (`rake site:sources`, ridden by
    # site:refresh): one row per LIVE PUBLIC source, complete by
    # construction. Two inputs, two natures — the AxisPages stance:
    #
    #   * MEMBERSHIP is the registry's — exactly the live-public rule
    #     SiteData#sources applies to site/_data/sources.yml
    #     (SiteData.live_public_slugs), so the table and the holdings data
    #     can never disagree about who is listed, and grant-gated blocked
    #     holdings never reach the page.
    #   * PROSE (the upstream credit, the contents line, the license
    #     statement) is CONTENT, hand-written per source in
    #     site/_data/source_notes.yml — read here, NEVER written. A note may
    #     carry `with: [slug, ...]` to fold sibling sources into one row
    #     (a corpus and its lexicon); a live source no note covers renders an
    #     honest pending row from its manifest (name, upstream link, license
    #     class) until its prose is written.
    #
    # The output is a PURE projection (registry + notes; holdings stay
    # Liquid, read from sources.yml at build), written to
    # site/_includes/sources_table.md, which site/sources.md includes. The
    # drift guard (test/site/sources_table_test.rb) regenerates it in memory
    # and fails the suite the day a live source is missing from the page.
    class SourcesTable
      NOTES_FILE = File.join("_data", "source_notes.yml")
      INCLUDE_FILE = File.join("_includes", "sources_table.md")
      HEADER = "| Source | Upstream project | Contents | Holdings (live) | License |"
      PENDING = "*Description pending.*"
      CELLS = %w[upstream contents license].freeze
      GENERATED_NOTE = "GENERATED by `rake site:sources` (Nabu::Ops::SourcesTable) from config/sources.yml " \
                       "+ site/_data/source_notes.yml — do not hand-edit; edit the notes and regenerate."

      def self.load(registry:, site_dir:)
        path = File.join(site_dir, NOTES_FILE)
        notes = File.exist?(path) ? YAML.safe_load_file(path) || {} : {}
        new(registry: registry, notes: notes, site_dir: site_dir)
      end

      def initialize(registry:, notes:, site_dir: nil)
        @registry = registry
        @notes = notes
        @site_dir = site_dir
      end

      # The live public slugs, sorted — the membership every row is cut from.
      def slugs
        @slugs ||= SiteData.live_public_slugs(@registry)
      end

      # Noted slugs (row keys and `with:` members) that are not live public
      # sources: their prose never renders (the guard names them so a
      # retired, renamed or blocked source's note does not rot unseen).
      def orphans
        (@notes.keys + @notes.values.flat_map { |note| Array(note["with"]) }).uniq.sort - slugs
      end

      # The live sources whose row still awaits its prose.
      def pending = row_groups.map(&:first).reject { |slug| @notes.key?(slug) }

      def render
        validate!
        rows = row_groups.map { |group| row(group) }
        "{% comment %}#{GENERATED_NOTE}{% endcomment %}\n" \
          "{% assign src = site.data.sources.sources -%}\n" \
          "#{HEADER}\n|---|---|---|---|---|\n#{rows.join}"
      end

      def write!(path = File.join(@site_dir, INCLUDE_FILE))
        FileUtils.mkdir_p(File.dirname(path))
        File.write(path, render)
        path
      end

      private

      # [primary, *members] per row, ordered by primary slug; a member folded
      # into a noted group never gets a row of its own.
      def row_groups
        live = slugs.to_h { |slug| [slug, true] }
        folded = @notes.select { |slug, _| live[slug] }.values.flat_map { |note| Array(note["with"]) }
        slugs.reject { |slug| folded.include?(slug) }.map do |slug|
          [slug, *Array(@notes.dig(slug, "with")).select { |member| live[member] }]
        end
      end

      def row(group)
        label = group.map { |slug| %(<span id="src-#{slug}"></span>) }.join + group.map { |s| "`#{s}`" }.join(", ")
        holdings = group.map { |slug| %({{ src["#{slug}"].holdings }}) }.join(" · ")
        upstream, contents, license = cells(group.first)
        "| #{label} | #{upstream} | #{contents} | #{holdings} | #{license} |\n"
      end

      def cells(slug)
        note = @notes[slug]
        return CELLS.map { |cell| note.fetch(cell).strip } if note

        manifest = entries.fetch(slug).manifest
        name = escape(manifest.name.to_s)
        url = manifest.upstream_url.to_s
        [url.empty? ? name : "[#{name}](#{url})", PENDING, "`#{manifest.license_class}`"]
      end

      def entries
        @entries ||= @registry.each_source.to_h { |entry| [entry.slug, entry] }
      end

      def escape(text) = text.gsub(/([|\[\]])/) { "\\#{::Regexp.last_match(1)}" }

      def validate!
        claims = @notes.flat_map { |slug, note| [slug, *Array(note["with"])] }
        twice = claims.tally.select { |_, count| count > 1 }.keys
        raise Error, "source_notes.yml notes these slugs twice: #{twice.join(', ')}" unless twice.empty?

        @notes.each do |slug, note|
          missing = CELLS.reject { |cell| note.is_a?(Hash) && !note[cell].to_s.strip.empty? }
          next if missing.empty?

          raise Error, "source_notes.yml #{slug} lacks #{missing.join(', ')}"
        end
      end
    end
  end
end
