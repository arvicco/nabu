# frozen_string_literal: true

require "yaml"
require_relative "source_class"

module Nabu
  module Ops
    module Reconstruction
      # The Reconstruction Book (docs/reconstruction.md): the ordered recipe
      # for rebuilding the whole library from a bare clone with no backup,
      # rendered from the registries — never hand prose. Inputs:
      #
      #   * the source registry + SourceClass verdicts (the class sections;
      #     blocked holdings are counted, never named — the public-census rule)
      #   * config/capabilities.yml (the non-derived layers of section 5)
      #   * the rake tools:* tasks (passed in by `rake reconstruction:book` —
      #     the executable surface of Nabu::ToolBootstrap) and the tool
      #     recipe docs under docs/manual/ that match no registered slug
      #   * site/_data/census.yml (the verification figures, as of its stamp)
      #
      # The verdicts read the INSTANCE (local/config/grants.yml, the
      # canonical/ attic), so the committed book is generated on the
      # reference instance and byte-refreshed at the gate, like site/_data;
      # the suite (test/ops/reconstruction/book_test.rb) guards its shape
      # and coverage from tracked inputs only.
      class Book
        OUTPUT_FILE = File.join("docs", "reconstruction.md")
        GENERATED_NOTE = "<!-- GENERATED by `rake reconstruction:book` (Nabu::Ops::Reconstruction::Book) from " \
                         "config/sources.yml, config/capabilities.yml, the tools:* tasks, docs/manual/ and " \
                         "site/_data/census.yml — do not hand-edit; edit the registries and regenerate. -->"
        ATTIC_HEADING = "### The attic — what no re-fetch restores"
        WRAP = 96

        # The sister repositories' read-back seams (CLAUDE.md, Sister
        # projects). The suite asserts every sister carries one.
        SISTER_SEAMS = {
          "nabu-lects" => %w[Nabu::Lects],
          "nabu-places" => %w[Nabu::Places],
          "nabu-data" => %w[Nabu::FormLemma Nabu::LanguageDossiers],
          "edubba-overlay" => %w[Nabu::EdubbaOverlay]
        }.freeze
        SISTER_URL = %r{\Ahttps://github\.com/arvicco/nabu-}

        CLASS_SECTIONS = {
          public_stable: ["Re-fetched from stable public URLs",
                          "The adapter fetches each of these unattended from stable public URLs. Enable, then " \
                          "sync: `bin/nabu enable SLUG && bin/nabu sync SLUG` (a group or axis name expands for " \
                          "both commands). The work is network-bound, so syncs run in parallel across sources " \
                          "and serially within one."],
          rail_paced: ["Re-crawled on the paced rail",
                       "Each upstream is harvested by a polite paced crawl that resumes slice by slice: a full " \
                       "re-crawl is months-class wall clock. `rake rail:plan` prints the lanes and " \
                       "`rake rail:step[SLUG]` runs one yield-guarded slice; one slice proves the recipe, the " \
                       "rest is calendar time."],
          manual: ["Re-acquired by a manual recipe",
                   "Upstream serves these only to a human. Each has its recipe in docs/manual/; the files are " \
                   "dropped where the recipe says, and `bin/nabu sync SLUG` loads them (until then the sync " \
                   "prints the acquisition card)."],
          granted: ["Re-fetched under a recorded license grant",
                    "Access rides a license grant from the source, recorded in the instance config; with it in " \
                    "place the adapter re-fetches like any other. Obtaining a grant is a matter between the " \
                    "instance holder and the source, outside this public page."],
          restricted: ["Re-obtained under the source's terms",
                       "The license class forbids redistribution, so there is no public mirror to fall back " \
                       "on: the asset must be re-obtained from the source under its terms."]
        }.freeze

        def self.from_config(config, tool_tasks:)
          root = Config::PROJECT_ROOT
          sources_path = File.join(root, "config", "sources.yml")
          manual_dir = File.join(root, "docs", "manual")
          classifier = SourceClass.new(sources_path: sources_path, manual_dir: manual_dir,
                                       grants_path: config.grants_path, canonical_dir: config.canonical_dir)
          new(registry: SourceRegistry.load(sources_path), verdicts: classifier.verdicts,
              capabilities: YAML.safe_load_file(File.join(root, "config", "capabilities.yml")),
              tool_tasks: tool_tasks, manual_dir: manual_dir,
              census: YAML.safe_load_file(File.join(root, "site", "_data", "census.yml")))
        end

        # The kind: module sources whose upstream is a sister repository.
        def self.sister_entries(registry)
          modules = registry.each_source.select { |entry| entry.kind == "module" }
          modules.select { |entry| entry.manifest.upstream_url.match?(SISTER_URL) }.sort_by(&:slug)
        end

        def initialize(registry:, verdicts:, capabilities:, tool_tasks:, manual_dir:, census:)
          @registry = registry
          @verdicts = verdicts
          @capabilities = capabilities
          @tool_tasks = tool_tasks
          @manual_dir = manual_dir
          @census = census
        end

        def render
          parts = [GENERATED_NOTE, "", "# Reconstruction Book", "", *intro, "", *prerequisites, "", *sisters, "",
                   *sources, "", *derivation, "", *enrichments, "", *verification, "",
                   "Instance-specific steps (credentials, correspondence with sources) live outside the public " \
                   "tree."]
          "#{parts.join("\n")}\n"
        end

        private

        def intro
          ["How would this whole library be rebuilt from a bare clone, with no backup? Everything under `db/` is " \
           "derived: one command, `bin/nabu rebuild`, regenerates it from the permanent folders. Everything under " \
           "`canonical/` is re-fetchable, each source by the route its class below names. Everything under " \
           "`local/` is the instance — rulings, grants and enrichment products — the part a reconstruction " \
           "re-decides or re-earns rather than re-downloads.",
           "",
           "This book is that recipe, in order. It is generated by `rake reconstruction:book` from the source " \
           "registry, the capability registry and the tool tasks, and the test suite guards its coverage. The " \
           "everyday restore paths (carrying a backup across, or a fresh `bin/nabu quickstart`) are in " \
           "[restore.md](restore.md)."]
        end

        def prerequisites
          lines = ["## 1 · Prerequisites and tools", "",
                   "Clone the repository and run `bundle install` (Ruby 3.3). The external tools the enrichment " \
                   "lanes run on install through one idempotent rake task each:", ""]
          @tool_tasks.each { |name, desc| lines << "- `rake #{name}` — #{desc}" }
          lines += ["", "The tool recipes, the human record of what those tasks do:", ""]
          unmatched_docs.reject { |_file, title| acquisition?(title) }
                        .each { |file, title| lines << "- [#{title}](manual/#{file})" }
          lines
        end

        def sisters
          lines = ["## 2 · The sister repositories", "",
                   "The sister repositories are `kind: module` sources like any other: `bin/nabu sync SLUG` " \
                   "fetches each into `canonical/<slug>/`, and Nabu reads it back through its seam.", ""]
          self.class.sister_entries(@registry).each do |entry|
            seams = SISTER_SEAMS.fetch(entry.slug, []).map { |seam| "`#{seam}`" }.join(", ")
            lines << "- `#{entry.slug}` — #{entry.manifest.upstream_url}, read through #{seams}"
          end
          lines
        end

        def sources
          lines = ["## 3 · The sources, by how they come back", "",
                   "Every registered source falls in exactly one class: the route by which its canonical asset " \
                   "would come back."]
          CLASS_SECTIONS.each do |klass, (title, recipe)|
            members = @verdicts.select { |verdict| verdict.klass == klass && !shelf?(verdict.slug) }
            lines += ["", "### #{title} — `#{klass}`, #{plural(members.size, 'source')}", "", recipe, ""]
            lines += class_list(klass, members)
          end
          lines + shelves + attic
        end

        def class_list(klass, members)
          listed, hidden = members.map { |verdict| @registry[verdict.slug] }.partition(&:public?)
          items = listed.map { |entry| item(klass, entry) }
          return ["None."] if items.empty? && hidden.empty?

          hidden_note = "plus #{hidden.size} not listed (grant-gated holdings that are not public)"
          return ["None listed, #{hidden_note}."] if items.empty?

          items[-1] = "#{items[-1]}, #{hidden_note}" unless hidden.empty?
          return wrap(items) unless klass == :manual

          items.map { |text| "- #{text}" } + further_recipes
        end

        # Acquisition recipes that serve no single registered slug (a family
        # of corpora, a library-shelf scan) ride under the manual class.
        def further_recipes
          docs = unmatched_docs.select { |_file, title| acquisition?(title) }
          return [] if docs.empty?

          ["", "Further acquisition recipes that serve no single registered source:", "",
           *docs.map { |file, title| "- [#{title}](manual/#{file})" }]
        end

        def item(klass, entry)
          case klass
          when :manual then "[`#{entry.slug}`](manual/#{entry.slug}.md)"
          when :restricted then "`#{entry.slug}` (#{entry.manifest.license_class})"
          else "`#{entry.slug}`"
          end
        end

        def shelves
          members = @registry.each_source.select { |entry| entry.kind == "shelf" }.map(&:slug).sort
          ["", "### The local shelves — #{plural(members.size, 'shelf')}", "",
           "The shelves are the instance's own holdings, kept under `local/`: no upstream serves them, so no " \
           "class above applies. They return only from a backup, or by being authored and filed anew.", "",
           *wrap(members.map { |slug| "`#{slug}`" })]
        end

        def attic
          slugs = @verdicts.select(&:attic).map(&:slug).sort
          lines = ["", ATTIC_HEADING, "",
                   "Some canonical trees keep files their upstream has since deleted, preserved under " \
                   "`canonical/<slug>/.attic/` by the fetch. These are the honest irreplaceables: no re-fetch " \
                   "restores those bytes, and a backup is the only route back for them. On the reference " \
                   "instance this book was generated from, #{plural(slugs.size, 'source')} carry an attic:", ""]
          lines + (slugs.empty? ? ["None."] : wrap(slugs.map { |slug| "`#{slug}`" }))
        end

        def derivation
          ["## 4 · Derivation", "",
           "`bin/nabu rebuild` drops every file under `db/` and regenerates it from the three permanent folders: " \
           "`canonical/` (the asset), `config/` (the project definition) and `local/` (the instance). It is run " \
           "deliberately, never by an automated pass, and it is hours-class on the full library. Afterward each " \
           "`bin/nabu sync` keeps the indexes current incrementally for the source it touches."]
        end

        def enrichments
          lines = ["## 5 · Enrichments", "",
                   "These are the layers `bin/nabu rebuild` deliberately does not regenerate (the cost law): each " \
                   "is re-acquired, re-decided or re-earned by its own command, at its own cost in time or money.",
                   "", "| Layer | Cost | Producer | Command | Home |", "| --- | --- | --- | --- | --- |"]
          @capabilities.fetch("layers").each do |name, layer|
            next if layer["cost"] == "derived"

            lines << "| `#{name}` | #{layer['cost']} | #{layer['producer']} | #{code(layer['command'])} | " \
                     "#{code(layer['home'])} |"
          end
          lines
        end

        def verification
          c = @census
          ["## 6 · Verification", "",
           "The published census is the reference a reconstruction is measured against. As of #{c['as_of']} it " \
           "stands at #{c['documents_display']} documents and #{c['passages_display']} passages in " \
           "#{c['language_codes']} language codes, across #{c['live_sources']} live sources of " \
           "#{c['registry_rows']} registry rows (`site/_data/census.yml`, regenerated by `rake site:refresh`). " \
           "Compare a rebuilt instance's `bin/nabu status` against those figures; `rake reconstruction:census` " \
           "prints its per-class source counts, its attic list and its `local/` inventory. A one-command " \
           "verification card is not yet part of the toolset."]
        end

        # docs/manual/*.md that name no registered slug: tool recipes, and
        # acquisition recipes for no single source (titled "— acquisition").
        def unmatched_docs
          Dir.glob(File.join(@manual_dir, "*.md")).filter_map do |path|
            file = File.basename(path)
            stem = File.basename(file, ".md")
            next if stem == "README" || @registry[stem]

            [file, title(path)]
          end
        end

        def title(path)
          heading = File.foreach(path).find { |line| line.start_with?("# ") }.to_s.delete_prefix("# ").strip
          heading.sub(/\s*\((?:P\d[^)]*)\)\s*\z/, "")
        end

        def acquisition?(title) = title.match?(/\bacquisition\b/i)

        def shelf?(slug) = @registry[slug]&.kind == "shelf"

        def code(text) = "`#{text.to_s.gsub('|', '\\|')}`"

        def plural(count, noun)
          word = if count == 1 then noun
                 elsif noun.end_with?("f") then "#{noun.delete_suffix('f')}ves"
                 else "#{noun}s"
                 end
          "#{count} #{word}"
        end

        # Comma-joined items wrapped near WRAP columns, ending in a period.
        def wrap(items)
          lines = [+""]
          items.each_with_index do |text, index|
            token = index == items.size - 1 ? "#{text}." : "#{text},"
            lines << +"" if !lines.last.empty? && lines.last.size + token.size + 1 > WRAP
            lines.last << (lines.last.empty? ? token : " #{token}")
          end
          lines
        end
      end
    end
  end
end
