# frozen_string_literal: true

require "json"

require_relative "../errors"
require_relative "../shell"

module Nabu
  module DataBuild
    # The repository README's dataset table, GENERATED between HTML-comment
    # markers from the registry and the built manifests. The table had been
    # hand-maintained and went stale (a whole release wave missing, counts
    # three releases old — owner correction 2026-10-17); the rail now
    # refreshes it after every build, so a new dataset cannot ship
    # unannounced on the repository's front page.
    #
    # One row per AVAILABLE feature whose dataset directory exists in the
    # clone: slug, registry title, the manifest's own row count (the data
    # resources' headline, never a hand pin), the dataset license, and the
    # Published date — the clone's own first-add commit date for the
    # dataset's manifest (an uncommitted dataset publishes today).
    module ReadmeIndex
      BEGIN_MARKER = "<!-- datasets:generated:begin -->"
      END_MARKER = "<!-- datasets:generated:end -->"

      Summary = Data.define(:listed, :missing)

      module_function

      # Rewrites the block between the markers in <out_dir>/README.md.
      # +published_dates+ maps slug => "YYYY-MM-DD"; pass the result of
      # .published_dates (the git provider) or any explicit mapping.
      # Features with no built directory are skipped and censused in the
      # returned Summary — never listed, never invented.
      def refresh!(features:, out_dir:, published_dates:)
        readme = File.join(out_dir, "README.md")
        text = File.read(readme)
        unless text.include?(BEGIN_MARKER) && text.include?(END_MARKER)
          raise Nabu::Error, "README.md carries no datasets:generated markers — " \
                             "add #{BEGIN_MARKER} / #{END_MARKER} around the dataset table"
        end

        rows = []
        missing = []
        features.select(&:available?).each do |feature|
          manifest = File.join(out_dir, feature.slug, "datapackage.json")
          next missing << feature.slug unless File.exist?(manifest)

          count = JSON.parse(File.read(manifest)).dig("nabu", "counts", "rows")
          rows << table_row(feature, count, published_dates[feature.slug])
        end

        block = <<~BLOCK.chomp
          #{BEGIN_MARKER}
          _This table is generated by the production rail (`nabu data build`)
          from the dataset registry and the built manifests — edit the
          registry, not the table._

          | Dataset | Content | License | Published |
          |---|---|---|---|
          #{rows.join("\n")}
          #{END_MARKER}
        BLOCK
        spliced = text.sub(/#{Regexp.escape(BEGIN_MARKER)}.*#{Regexp.escape(END_MARKER)}/m, block)
        File.write(readme, spliced)
        Summary.new(listed: rows.size, missing: missing)
      end

      # slug => "YYYY-MM-DD": the first-add commit date of the dataset's
      # manifest in the clone's own history; a dataset git has never seen
      # is being published now, so it dates today.
      def published_dates(out_dir:, slugs:)
        slugs.to_h do |slug|
          log = Nabu::Shell.run("git", "-C", out_dir, "log", "--diff-filter=A", "--follow",
                                "--format=%as", "--", "#{slug}/datapackage.json")
          first = log.split("\n").reject(&:empty?).last
          [slug, first || Time.now.strftime("%Y-%m-%d")]
        end
      end

      def table_row(feature, count, published)
        content = +feature.title.to_s
        content << " — #{format_count(count)} rows" if count
        "| `#{feature.slug}` | #{content} | #{human_license(feature.license)} | #{published} |"
      end

      def format_count(count) = count.to_s.gsub(/(\d)(?=(\d{3})+\z)/, '\1,')

      def human_license(license) = license.to_s.sub("CC-BY-SA-4.0", "CC BY-SA 4.0").sub("CC-BY-4.0", "CC BY 4.0")
    end
  end
end
