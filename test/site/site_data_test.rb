    # The hand-number guard: the MCP page and the Tools page READ the tool
    # list; a spelled or digit tool count in their prose is the drift this
    # data file exists to kill ("fourteen tools" outlived two tool mints).
    # Registry-scale counts only (ten and up): "two or three tools" is
    # prose about composing calls, not a census.
    def test_the_mcp_and_tools_pages_render_the_tool_list_from_data
      mcp_page = File.read(File.join(ROOT, "site", "mcp.md"))
      tools_page = File.read(File.join(ROOT, "site", "tools.md"))
      assert mcp_page.include?("site.data.mcp.tools"), "the MCP page loops over site.data.mcp.tools"
      assert tools_page.include?("site.data.mcp.tool"), "the Tools page reads the tool list from data"
      count_words = %w[ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen
                       twenty thirty].join("|")
      hand_count = /\b(?:#{count_words}|\d{2,})(?:-\w+)?\s+(?:MCP\s+)?tools\b/i
      { "mcp.md" => mcp_page, "tools.md" => tools_page }.each do |name, text|
        refute hand_count.match?(text), "site/#{name} states a hand-written tool count (#{text[hand_count]}) — " \
                                        "render site.data.mcp.tool_count"
      end
      assert hand_count.match?("exposing fourteen tools"), "the guard must catch the retired phrasing"
      refute hand_count.match?("usually two or three tools"), "composition prose must pass"
      refute mcp_page.include?("ghcr.io/arvicco/nabu-demo"),
             "every image reference on the MCP page renders site.data.mcp (the pinned tag)"
    end

