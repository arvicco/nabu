                   "the registry SHAPE (rows by kind) still counts every row"
    end

    # -- the per-source grain (sources.yml) -------------------------------------

    # A stand-in for the du-backed Disk probe: canned kilobyte figures per
    # canonical child, so the projection is testable without shelling out.
    class FakeDisk
      def initialize(kilobytes)
        @kb = kilobytes
      end

      def tree_kb(dir) = @kb.transform_keys { |name| File.join(dir, name) }
    end

    def seed_sources_catalog(dir)
      path = File.join(dir, "catalog.sqlite3")
      catalog = Nabu::Store.connect("sqlite://#{path}")
      Nabu::Store.migrate!(catalog)
      ids = {}
      { "cdli" => "attribution", "oracc" => "open", "titus-avestan" => "nc",
        "lexica" => "attribution" }.each do |slug, license|
        ids[slug] = catalog[:sources].insert(slug: slug, name: "#{slug.upcase} — the shelf",
                                             adapter_class: "X", license_class: license)
      end
      { "cdli" => [1_234, 56_789], "oracc" => [10, 200], "titus-avestan" => [5, 50] }.each do |slug, (docs, pas)|
        catalog[:source_stats].insert(source_id: ids[slug], live_documents: docs, live_passages: pas,
                                      updated_at: Time.now, note: "seeded")
      end
      dict = catalog[:dictionaries].insert(source_id: ids["lexica"], slug: "lsj", title: "LSJ", language: "grc")
      3.times do |i|
        catalog[:dictionary_entries].insert(dictionary_id: dict, urn: "urn:d:#{i}", entry_id: "e#{i}",
                                            key_raw: "k", headword: "h", headword_folded: "h", body: "b",
                                            content_sha256: "x", withdrawn: i == 2)
      end
      catalog.disconnect
      File.write(File.join(dir, "shelf_members.yml"), { "cuneiform" => %w[oracc cdli] }.to_yaml)
      path
    end

    def seeded_sources(dir, disk: nil)
      path = seed_sources_catalog(dir)
      canonical = disk && File.join(dir, "canonical")
      Nabu::Ops::SiteData.new(registry: registry, data_dir: dir, catalog_path: path,
                              canonical_dir: canonical, disk: disk, as_of: Date.new(2026, 11, 3)).sources
    end

